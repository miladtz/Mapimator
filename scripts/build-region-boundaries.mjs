import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const REVISION = 'ca96624a56bd078437bca8184e78163e5039ad19';
const BASE = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${REVISION}/geojson`;
const sources = [
  ['country', 'ne_50m_admin_0_countries.geojson'],
  ['admin1', 'ne_50m_admin_1_states_provinces.geojson'],
];
const features = [];
const provenance = [];
for (const [kind, filename] of sources) {
  const response = await fetch(`${BASE}/${filename}`);
  if (!response.ok) throw new Error(`${filename}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  const collection = JSON.parse(bytes.toString('utf8'));
  provenance.push({ filename, sha256: createHash('sha256').update(bytes).digest('hex') });
  for (const feature of collection.features) {
    if (!['Polygon', 'MultiPolygon'].includes(feature.geometry?.type)) continue;
    const p = feature.properties ?? {};
    const countryCode = String(p.ADM0_A3 || p.adm0_a3 || p.SOV_A3 || p.sov_a3 || p.ISO_A3 || '').toUpperCase();
    const countryCode2 = String(p.ISO_A2 || p.iso_a2 || '').toLowerCase();
    const adminCode = kind === 'admin1' ? String(p.iso_3166_2 || p.ISO_3166_2 || p.adm1_code || p.ADM1_CODE || '') : undefined;
    const id = kind === 'country' ? countryCode : adminCode || String(p.adm1_code || p.ADM1_CODE || p.name || p.NAME || '');
    features.push({ type: 'Feature', geometry: feature.geometry, properties: {
      id, kind, name: String(p.NAME_EN || p.name_en || p.NAME || p.name || id), localName: String(p.NAME || p.name || ''),
      countryCode, countryCode2, continent: String(p.CONTINENT || ''), adminCode,
      wikidataId: p.WIKIDATAID || p.wikidataid || p.wikidata || undefined,
    }});
  }
}
features.sort((a, b) => `${a.properties.kind}:${a.properties.id}`.localeCompare(`${b.properties.kind}:${b.properties.id}`));
const output = `/* Generated by scripts/build-region-boundaries.mjs. Natural Earth public domain. */\n` +
  `export const REGION_BOUNDARY_PROVENANCE = ${JSON.stringify({ revision: REVISION, license: 'Public domain', sources: provenance })} as const;\n` +
  `export const REGION_BOUNDARIES = ${JSON.stringify({ type: 'FeatureCollection', features })} as const;\n`;
await writeFile(new URL('../src/data/regionBoundaries.ts', import.meta.url), output);
console.log(`Wrote ${features.length} canonical boundaries (${Buffer.byteLength(output)} bytes).`);
